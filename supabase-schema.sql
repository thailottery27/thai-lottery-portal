-- ==============================================================================
-- ENABLE ROW LEVEL SECURITY (RLS) & PUBLIC ACCESS POLICIES
-- ==============================================================================
ALTER TABLE public.site_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.winning_papers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payment_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_reviews ENABLE ROW LEVEL SECURITY;

-- Policies for site_settings
CREATE POLICY "Allow public read site_settings" ON public.site_settings FOR SELECT USING (true);
CREATE POLICY "Allow public update site_settings" ON public.site_settings FOR UPDATE USING (true);

-- Policies for winning_papers
CREATE POLICY "Allow public read winning_papers" ON public.winning_papers FOR SELECT USING (true);
CREATE POLICY "Allow public insert winning_papers" ON public.winning_papers FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public delete winning_papers" ON public.winning_papers FOR DELETE USING (true);

-- Policies for payment_requests
CREATE POLICY "Allow public read payment_requests" ON public.payment_requests FOR SELECT USING (true);
CREATE POLICY "Allow public insert payment_requests" ON public.payment_requests FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update payment_requests" ON public.payment_requests FOR UPDATE USING (true);
CREATE POLICY "Allow public delete payment_requests" ON public.payment_requests FOR DELETE USING (true);

-- Policies for user_reviews
CREATE POLICY "Allow public read user_reviews" ON public.user_reviews FOR SELECT USING (true);
CREATE POLICY "Allow public insert user_reviews" ON public.user_reviews FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update user_reviews" ON public.user_reviews FOR UPDATE USING (true);
CREATE POLICY "Allow public delete user_reviews" ON public.user_reviews FOR DELETE USING (true);

-- ==============================================================================
